{
    /// <summary>Text moves on five pixels a character; the glyphs carry their own gap.</summary>
    private const int GlyphAdvance = 5;

    /// <summary>
    /// text.bmp's three rows of 31 cells, in the order every classic skin
    /// uses (webamp's FONT_LOOKUP). Spaces are blank cells, so row 0's cells
    /// 28 and 29 and the end of row 2 stay empty, as in other skins.
    /// </summary>
