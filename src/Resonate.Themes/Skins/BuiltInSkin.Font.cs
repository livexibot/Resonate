    [
        "ABCDEFGHIJKLMNOPQRSTUVWXYZ\"@   ",
        "0123456789….:()-'!_+\\/[]^&%,=$#",
        "ÅÖÄ?*",
    ];

    /// <summary>
    /// A character of the 5x6 font: mostly four pixels wide and five tall,
    /// with the fifth column and sixth row left for the gap (a few wide
    /// letters use all five columns; the comma and underscore reach the sixth
    /// row). Unknown characters are blank.
    /// </summary>
