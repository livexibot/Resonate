    private static string LampGlyph(char c) => c switch
    {
        'S' => ".##/#../.#./..#/##.",
        'T' => "###/.#./.#./.#./.#.",
        'E' => "###/#../##./#../###",
        'R' => "##./#.#/##./#.#/#.#",
